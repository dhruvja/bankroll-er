/** Emits programs/bankroll/src/board.rs from shared/board.json. `--check` fails if the file is stale. */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { board, type Board } from '../shared/board';

const GROUPS = ['Brown', 'Sky', 'Pink', 'Orange', 'Green', 'Gold', 'Public'];
const KINDS: Record<string, string> = { start: 'Start', city: 'City', lucky: 'Lucky', public: 'Public', jail: 'Jail', auction: 'Auction' };
export const BOARD_RS = resolve(import.meta.dirname, '../programs/bankroll/src/board.rs');

export function renderBoardRs(source: Board): string {
  const rules = source.rules, steps = rules.seatBonusStepByTarget, deadlines = rules.deadlinesSec;
  const spaces = source.spaces.map(space => {
    const group = space.group ? GROUPS.indexOf(space.group) + 1 : 0;
    return `    SpaceSpec { kind: SpaceKind::${KINDS[space.kind]}, group: ${group}, price: ${space.price ?? 0}, rent: ${space.rent ?? 0}, building_cost: ${space.buildingCost ?? 0} },`;
  });
  const groupSizes = [0, ...GROUPS.map(name => name === 'Public' ? source.publics.length : source.groups[name].length)];
  return `// Generated by scripts/gen-board.ts from shared/board.json (phase 01 frozen economy). Do not edit.
use crate::state::{SpaceKind, SpaceSpec};

pub const SPACES: usize = ${source.spaces.length};
pub const PUBLIC_GROUP: u8 = ${GROUPS.indexOf('Public') + 1};
pub const GROUP_SIZES: [u8; ${groupSizes.length}] = [${groupSizes.join(', ')}];
pub const START_CASH: i64 = ${rules.startCash};
pub const SALARY: i64 = ${rules.salary};
pub const BANKRUPT_CASH_BELOW: i64 = ${rules.bankruptCashBelow};
pub const MAX_ROLLS_PER_TURN: u8 = ${rules.maxRollsPerTurn};
pub const GROUP_RENT_MULTIPLIER: i64 = ${rules.groupRentMultiplier};
pub const BUILDING_RENT_MULTIPLIERS: [i64; 3] = [${rules.buildingRentMultipliers.join(', ')}];
pub const TARGETS: [u64; 3] = [${rules.targets.join(', ')}];
pub const SEAT_BONUS_STEPS: [i64; 3] = [${rules.targets.map(target => steps[String(target)]).join(', ')}];
pub const PREROLL_SECONDS: i64 = ${deadlines.preRoll};
pub const BUY_SECONDS: i64 = ${deadlines.buyDecision};
pub const VRF_RETRY_SECONDS: i64 = ${deadlines.vrfRetry};
pub const IDLE_SECONDS: i64 = ${deadlines.idle};
pub const EMERGENCY_SECONDS: i64 = ${deadlines.emergencyRefundAfterIdle};
pub const STRIKES_TO_FORFEIT: u8 = ${rules.strikesToForfeit};

pub const BOARD: [SpaceSpec; SPACES] = [
${spaces.join('\n')}
];
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const rendered = renderBoardRs(board);
  if (process.argv.includes('--check')) {
    if (readFileSync(BOARD_RS, 'utf8') !== rendered) throw new Error('board.rs is stale; run pnpm gen-board.');
    console.log('board.rs matches shared/board.json');
  } else {
    writeFileSync(BOARD_RS, rendered);
    console.log(`wrote ${BOARD_RS}`);
  }
}
